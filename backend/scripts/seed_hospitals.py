async def seed_hospitals():
    async with async_session_factory() as session:
        added = 0
        skipped = 0

        for data in HOSPITALS:
            result = await session.execute(
                select(Hospital).where(
                    Hospital.registration_number == data["registration_number"]
                )
            )

            existing = result.scalar_one_or_none()

            if existing:
                skipped += 1
                print(f"SKIP: {data['name']}")
                continue

            hospital = Hospital(**data)
            session.add(hospital)
            added += 1
            print(f"ADD:  {data['name']}")

        await session.commit()

        print("\n" + "=" * 50)
        print(f"Hospitals added : {added}")
        print(f"Hospitals skipped: {skipped}")
        print(f"Total seed data : {len(HOSPITALS)}")
        print("=" * 50)


if __name__ == "__main__":
    asyncio.run(seed_hospitals())